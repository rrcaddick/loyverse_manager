#!/usr/bin/env node
/**
 * Writes src/styles/tokens.css: the Material 2 tokens for the default pair
 * (Indigo 500 + Pink A200) in light (:root) and dark (.dark), so the first
 * paint is right before the runtime applies the user's own pair
 * (src/lib/appearance.ts sets the same variables inline on <html>).
 *
 *   node scripts/gen-m2-tokens.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DEFAULT_PAIR, tokensFor } from "../src/styles/m2.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "../src/styles/tokens.css");

function block(selector, mode) {
  const t = tokensFor(DEFAULT_PAIR, mode);
  const lines = [`${selector} {`];
  for (const [k, v] of Object.entries(t)) lines.push(`  --${k}: ${v};`);
  lines.push(`  color-scheme: ${mode};`, "}");
  return lines.join("\n");
}

const css = `/*
 * Farmyard Bookings tokens — GENERATED by scripts/gen-m2-tokens.mjs from
 * src/styles/m2.mjs (Material Design 2). Do not edit by hand.
 *
 * These are the defaults for Indigo + Pink. The user's own swatch pair is
 * applied at runtime by setting the same variables inline on <html>.
 */

${block(":root", "light")}

${block(".dark", "dark")}

/* ------------------------------------------------------------- text size */
html { font-size: 17px; }
html[data-text-size="default"] { font-size: 16px; }
html[data-text-size="large"] { font-size: 17px; }
html[data-text-size="xlarge"] { font-size: 18px; }
`;
writeFileSync(OUT, css);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${css.split("\n").length} lines)`);
